    // ────────── Fixture ──────────

    private static Fixture fixture(int moveInterval, Position enemyPosition,
                                   Position playerPosition, int sightRange) {
        TETile[][] world = corridorWorld(20, 3);
        EntityManager entityMgr = new EntityManager();
        Player player = new Player(playerPosition, 100, 10);
        Enemy enemy = new Enemy(enemyPosition, Tileset.ENEMY,
                20, sightRange, moveInterval, 1, 0,
                new Random(42), "guard-a");
        entityMgr.addEntity(player);
        entityMgr.addEntity(enemy);
        return new Fixture(world, entityMgr, player, enemy);
    }

    private static TETile[][] corridorWorld(int width, int height) {
        TETile[][] world = new TETile[width][height];
        for (int x = 0; x < width; x++) {
            for (int y = 0; y < height; y++) {
                world[x][y] = y == 1 ? Tileset.FLOOR : Tileset.WALL;
            }
        }
        return world;
    }

    private static final class Fixture {
        private final TETile[][] world;
        private final EntityManager entityMgr;
        private final Player player;
        private final Enemy enemy;

        private Fixture(TETile[][] world, EntityManager entityMgr,
                        Player player, Enemy enemy) {
            this.world = world;
            this.entityMgr = entityMgr;
            this.player = player;
            this.enemy = enemy;
        }

        private AiTickContext context(long tick) {
            return new AiTickContext(RUN_ID, FLOOR_ID, tick);
        }

        private void prime() {
            entityMgr.flushPendingChanges();
            enemy.collectAgentUpdates(context(0), world, entityMgr, player);
        }

        private void tick(long tick) {
            AiTickContext ctx = context(tick);
            enemy.pollAgentMessages(ctx);
            enemy.executeOneAction(ctx, world, entityMgr);
            entityMgr.flushPendingChanges();
            entityMgr.removeDeadEntities();
            enemy.collectAgentUpdates(ctx, world, entityMgr, player);
        }

        /**
         * 手动重跑一次 collectAgentUpdates，把当前玩家位置固化为 latestReflexObservation。
         * 生产帧序是 execute→collect，下一 tick 的 execute 才会读到新观察；
         * 测试在两次 tick 之间挪动玩家后调用此方法，等效于"上一帧 collect 已捕获新状态"。
         * 注意：Entity.setPosition 只改实体字段，不重建 EntityManager 索引，
         * 所以必须先 flushPendingChanges 让索引同步，否则 perception 查不到玩家新位置。
         */
        private void refreshObservation() {
            entityMgr.flushPendingChanges();
            enemy.collectAgentUpdates(context(0), world, entityMgr, player);
        }

        /** Adopt a remote CHASE intent targeting the given position. */
        private DecisionValidator.ValidationResult adoptChase(
                String decisionId, long observationSeq, Position target) {
            return adoptIntent(decisionId, observationSeq,
                    AgentProtocol.Skill.CHASE, target, true);
        }

        /** Adopt a remote PATROL intent targeting the given position. */
        private DecisionValidator.ValidationResult adoptPatrol(
                String decisionId, long observationSeq, Position target) {
            return adoptIntent(decisionId, observationSeq,
                    AgentProtocol.Skill.PATROL, target, true);
        }

        private DecisionValidator.ValidationResult adoptPatrolWithTtl(
                String decisionId, Position target, int validForTicks) {
            ObservationEnvelope source = enemy.getLatestObservation();
            return adoptIntentFromObservation(
                    decisionId, source,
                    AgentProtocol.Skill.PATROL, target,
                    true, validForTicks, 0);
        }

        private DecisionValidator.ValidationResult adoptPatrolFromObservation(
                String decisionId,
                ObservationEnvelope sourceObservation,
                Position target,
                long currentLogicalTick) {
            return adoptIntentFromObservation(
                    decisionId, sourceObservation,
                    AgentProtocol.Skill.PATROL, target,
                    true, 20, currentLogicalTick);
        }

        /** Adopt a remote GUARD intent with configurable engageVisiblePlayer. */
        private DecisionValidator.ValidationResult adoptGuard(
                String decisionId, long observationSeq, Position target,
                boolean engageVisiblePlayer) {
            return adoptIntent(decisionId, observationSeq,
                    AgentProtocol.Skill.GUARD, target, engageVisiblePlayer);
        }

        private DecisionValidator.ValidationResult adoptGuardWithTtl(
                String decisionId, Position target,
                boolean engageVisiblePlayer, int validForTicks) {
            ObservationEnvelope source = enemy.getLatestObservation();
            return adoptIntentFromObservation(
                    decisionId, source,
                    AgentProtocol.Skill.GUARD, target,
                    engageVisiblePlayer, validForTicks, 0);
        }

        private DecisionValidator.ValidationResult adoptIntent(
                String decisionId, long observationSeq,
                AgentProtocol.Skill skill, Position target,
                boolean engageVisiblePlayer) {
            ObservationEnvelope source = enemy.getLatestObservation();
            assertEquals("test request must use the captured observation",
                    observationSeq, source.getObservationSeq());
            return adoptIntentFromObservation(
                    decisionId, source, skill, target,
                    engageVisiblePlayer, 20, 0);
        }

        private DecisionValidator.ValidationResult adoptIntentFromObservation(
                String decisionId,
                ObservationEnvelope sourceObservation,
                AgentProtocol.Skill skill,
                Position target,
                boolean engageVisiblePlayer,
                int validForTicks,
                long currentLogicalTick) {

            Map<String, Object> params = new LinkedHashMap<>();
            params.put("targetPosition",
                    new AgentProtocol.PositionData(target.x, target.y));

            AgentProtocol.InterruptPolicyData policy =
                    new AgentProtocol.InterruptPolicyData(
                            engageVisiblePlayer, true, true);

            AgentProtocol.IntentData intent = new AgentProtocol.IntentData(
                    AgentProtocol.INTENT_VERSION, skill, params,
                    0.8, validForTicks, policy);

            AgentProtocol.SubmitIntentData proposal =
                    new AgentProtocol.SubmitIntentData(
                            decisionId,
                            sourceObservation.getObservationSeq(),
                            REQUEST_GENERATION,
                            intent);

            AgentProtocol.Envelope envelope = new AgentProtocol.Envelope(
                    AgentProtocol.ENVELOPE_VERSION,
                    "msg-1", 0,
                    "world-test", RUN_ID, FLOOR_ID, "guard-a",
                    SESSION_EPOCH, 0,
                    AgentProtocol.MessageType.SUBMIT_INTENT,
                    proposal);

            DecisionValidator.RequestExpectation expectation =
                    new DecisionValidator.RequestExpectation(
                            new AgentProtocol.Identity(
                                    "world-test", RUN_ID, FLOOR_ID, "guard-a",
                                    SESSION_EPOCH, REQUEST_GENERATION),
                            decisionId,
                            sourceObservation.getObservationSeq(),
                            REQUEST_GENERATION,
                            sourceObservation);

            return enemy.tryAdoptRemoteIntent(
                    proposal, envelope, expectation,
                    world, currentLogicalTick);
        }
    }
