    // ────────── Arbiter-A05 ──────────

    /**
     * Arbiter-A05: when the player enters FOV while the agent is waiting,
     * the next action tick triggers P2 reflex engage.
     */
    @Test
    public void visible_player_triggers_next_action_tick() {
        // Player far away, not visible initially
        Fixture fixture = fixture(1, new Position(1, 1),
                new Position(15, 1), 10);
        fixture.prime();

        // Adopt PATROL lease (player not visible -> not stale)
        DecisionValidator.ValidationResult result = fixture.adoptPatrol(
                "decision-1", 0, new Position(5, 1));
        assertEquals(DecisionValidator.ValidationResult.ACCEPTED, result);

        // Execute tick 0: P3 (player not visible, no P2)
        fixture.tick(0);
        ActionOutcome outcome0 = fixture.enemy.getLastActionOutcome();
        assertNull(outcome0.getOverrideReason());

        // Move player into FOV
        fixture.player.setPosition(new Position(5, 1));
        // 刷新 observation：生产帧序中，玩家移动后的状态由本帧末尾的 collect 捕获，
        // 下一帧 execute 才会读到。这里手动刷新等效于跨过了那一道帧边界。
        fixture.refreshObservation();

        // Tick 1: execute uses refreshed observation -> P2 triggers
        fixture.tick(1);
        ActionOutcome outcome1 = fixture.enemy.getLastActionOutcome();
        assertNotNull(outcome1);
        assertEquals("P2_VISIBLE_PLAYER", outcome1.getOverrideReason());
        // P2 reflex action should move toward player
        assertEquals("MoveAction", outcome1.getActionType());
    }

    // ────────── Arbiter-A06 ──────────

    /**
     * Arbiter-A06: GUARD policy with engageVisiblePlayer=false limits P2 but not P1.
     * Player visible but not adjacent -> P2 suppressed, P3 used.
     * Player adjacent -> P1 still triggers.
     */
    @Test
    public void fresh_guard_policy_limits_p2_not_p1() {
        // Player at distance 2, visible but not adjacent
        Fixture fixture = fixture(1, new Position(1, 1),
                new Position(3, 1), 10);
        fixture.prime();

        // Adopt GUARD lease with engageVisiblePlayer=false
        DecisionValidator.ValidationResult result = fixture.adoptGuard(
                "decision-1", 0, new Position(5, 1),
                false);
        assertEquals(DecisionValidator.ValidationResult.ACCEPTED, result);

        // Execute tick 0: P2 should NOT trigger (policy disallows)
        fixture.tick(0);
        ActionOutcome outcome0 = fixture.enemy.getLastActionOutcome();
        assertNotNull(outcome0);
        // P3 used (no reflex override)
        assertNull(outcome0.getOverrideReason());
        assertEquals(AgentProtocol.DecisionSource.REMOTE_AGENT,
                outcome0.getDecisionSource());

        // Move player adjacent to enemy's new position
        Position enemyPos = fixture.enemy.getPosition();
        fixture.player.setPosition(new Position(enemyPos.x + 1, enemyPos.y));

        // Tick 1: P1 should trigger (adjacent, regardless of policy)
        fixture.tick(1);
        ActionOutcome outcome1 = fixture.enemy.getLastActionOutcome();
        assertNotNull(outcome1);
        assertEquals("P1_ADJACENT_THREAT", outcome1.getOverrideReason());
        assertEquals("AttackAction", outcome1.getActionType());
    }

