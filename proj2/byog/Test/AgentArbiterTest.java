    /**
     * Arbiter-A01: remote CHASE intent goes through Validator/Lease/Planner.
     * The action is generated by Java's ClassicalPlanner, not directly by Python.
     */
    @Test
    public void remote_intent_goes_through_java_planner() {
        Fixture fixture = fixture(1, new Position(1, 1),
                new Position(5, 1), 10);
        fixture.prime();

        // Adopt a remote CHASE intent targeting the visible player
        DecisionValidator.ValidationResult result = fixture.adoptChase(
                "decision-1", 0, new Position(5, 1));
        assertEquals(DecisionValidator.ValidationResult.ACCEPTED, result);

        fixture.tick(0);

        ActionOutcome outcome = fixture.enemy.getLastActionOutcome();
        assertNotNull(outcome);
        assertEquals(AgentProtocol.DecisionSource.REMOTE_AGENT,
                outcome.getDecisionSource());
        assertEquals("MoveAction", outcome.getActionType());
        // Enemy should have moved toward the player
        assertEquals(new Position(2, 1), fixture.enemy.getPosition());
    }

