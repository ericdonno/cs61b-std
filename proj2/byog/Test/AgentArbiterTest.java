    /**
     * Arbiter-A08: when the player leaves FOV, the reflex override ends.
     * The fast brain does not read the hidden player position.
     * The old lease only resumes if its precondition still holds.
     */
    @Test
    public void hidden_player_position_not_used() {
        // Player visible initially
        Fixture fixture = fixture(1, new Position(1, 1),
                new Position(3, 1), 10);
        fixture.prime();

        // Adopt a CHASE lease (player visible -> not stale)
        DecisionValidator.ValidationResult result = fixture.adoptChase(
                "decision-1", 0, new Position(3, 1));
        assertEquals(DecisionValidator.ValidationResult.ACCEPTED, result);
        IntentLease remoteLease =
                fixture.enemy.getArbiter().getCurrentLease();

        // Tick 0: P2 triggers (CHASE lease, player visible)
        fixture.tick(0);
        ActionOutcome outcome0 = fixture.enemy.getLastActionOutcome();
        assertEquals("P2_VISIBLE_PLAYER", outcome0.getOverrideReason());

        // Move player far away (out of FOV)
        fixture.player.setPosition(new Position(15, 1));
        // 刷新 observation：让 latestReflexObservation 反映玩家已离开 FOV
        fixture.refreshObservation();

        // Tick 1: execute uses refreshed observation -> P2 no longer triggers, override ends
        fixture.tick(1);
        ActionOutcome outcome1 = fixture.enemy.getLastActionOutcome();
        // Override should have ended
        assertNull(outcome1.getOverrideReason());

        // 原远程 lease 必须明确失效，并由新的本地 lease 接管。
        assertEquals(IntentLease.LeaseState.STALE,
                remoteLease.getState());
        IntentLease currentLease =
                fixture.enemy.getArbiter().getCurrentLease();
        assertNotNull(currentLease);
        assertNotSame(remoteLease, currentLease);
        assertEquals(AgentProtocol.DecisionSource.LOCAL_FALLBACK,
                currentLease.getDecisionSource());
        assertEquals(AgentProtocol.DecisionSource.LOCAL_FALLBACK,
                outcome1.getDecisionSource());
    }

