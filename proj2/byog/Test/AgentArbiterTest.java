    /**
     * Arbiter-A07: a stale PATROL intent (based on old observation without player)
     * cannot override the current reflex engage when player is visible.
     */
    @Test
    public void stale_patrol_cannot_override_reflex_engage() {
        // 请求产生时玩家不可见，PATROL 当时合法。
        Fixture fixture = fixture(1, new Position(1, 1),
                new Position(15, 1), 10);
        fixture.prime();
        ObservationEnvelope oldObservation =
                fixture.enemy.getLatestObservation();

        // 等待期间玩家进入 FOV。
        fixture.player.setPosition(new Position(5, 1));
        fixture.refreshObservation();

        // 当前 tick 先触发 P2。
        fixture.tick(1);
        ActionOutcome outcome0 = fixture.enemy.getLastActionOutcome();
        assertEquals("P2_VISIBLE_PLAYER", outcome0.getOverrideReason());

        // 迟到 PATROL 仍基于旧 observation，不能覆盖当前反射。
        DecisionValidator.ValidationResult result =
                fixture.adoptPatrolFromObservation(
                        "decision-1", oldObservation,
                        new Position(5, 1), 2);
        assertEquals(DecisionValidator.ValidationResult.STALE_PRECONDITION,
                result);

        // No lease adopted, P2 reflex continues
        assertNull(fixture.enemy.getArbiter().getCurrentLease());

        fixture.tick(2);
        ActionOutcome outcome1 = fixture.enemy.getLastActionOutcome();
        assertEquals("P2_VISIBLE_PLAYER", outcome1.getOverrideReason());
    }

