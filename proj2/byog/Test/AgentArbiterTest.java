    @Test
    public void lease_terminal_states_and_target_are_immutable() {
        Position target = new Position(5, 1);
        byog.AI.StrategicIntent intent = new byog.AI.StrategicIntent(
                byog.AI.StrategicIntent.Goal.PATROL,
                byog.AI.StrategicIntent.Strategy.PATROL,
                target);
        IntentLease stale = new IntentLease(
                intent, "decision-stale", 0, 0, 2,
                byog.AI.InterruptPolicy.safeDefault(),
                AgentProtocol.DecisionSource.REMOTE_AGENT);

        target.x = 99;
        assertEquals(new Position(5, 1),
                stale.getIntent().getTargetPosition());
        Position returned = stale.getIntent().getTargetPosition();
        returned.x = 77;
        assertEquals(new Position(5, 1),
                stale.getIntent().getTargetPosition());

        stale.markStale();
        stale.markExpired();
        assertEquals(IntentLease.LeaseState.STALE, stale.getState());
        assertFalse(stale.resumeAt(0));

        IntentLease expired = new IntentLease(
                intent, "decision-expired", 0, 0, 1,
                byog.AI.InterruptPolicy.safeDefault(),
                AgentProtocol.DecisionSource.REMOTE_AGENT);
        expired.refreshExpiry(1);
        expired.markStale();
        assertEquals(IntentLease.LeaseState.EXPIRED,
                expired.getState());
        assertFalse(expired.resumeAt(1));
    }

