    /**
     * Arbiter-A02: rejected intent has no side effects on lease/queue/cooldown.
     */
    @Test
    public void invalid_intent_has_no_side_effects() {
        Fixture fixture = fixture(1, new Position(1, 1),
                new Position(15, 1), 10);
        fixture.prime();

        assertEquals(DecisionValidator.ValidationResult.ACCEPTED,
                fixture.adoptPatrol(
                        "decision-1", 0, new Position(5, 1)));
        fixture.tick(0);

        IntentLease leaseBefore =
                fixture.enemy.getArbiter().getCurrentLease();
        IntentLease.LeaseState stateBefore = leaseBefore.getState();
        int queueSizeBefore = fixture.enemy.getActionQueue().size();
        Position positionBefore = fixture.enemy.getPosition();
        int hpBefore = fixture.enemy.getHp();
        boolean overrideBefore =
                fixture.enemy.getArbiter().isInReflexOverride();
        String overrideReasonBefore =
                fixture.enemy.getArbiter().getOverrideReason();
        ActionOutcome outcomeBefore =
                fixture.enemy.getLastActionOutcome();

        // Try to adopt an intent with out-of-bounds target
        DecisionValidator.ValidationResult result = fixture.adoptChase(
                "decision-2",
                fixture.enemy.getLatestObservation().getObservationSeq(),
                new Position(999, 999));
        assertEquals(DecisionValidator.ValidationResult.TARGET_OUT_OF_BOUNDS,
                result);

        assertSame(leaseBefore,
                fixture.enemy.getArbiter().getCurrentLease());
        assertEquals(stateBefore, leaseBefore.getState());
        assertEquals(queueSizeBefore,
                fixture.enemy.getActionQueue().size());
        assertEquals(positionBefore, fixture.enemy.getPosition());
        assertEquals(hpBefore, fixture.enemy.getHp());
        assertEquals(overrideBefore,
                fixture.enemy.getArbiter().isInReflexOverride());
        assertEquals(overrideReasonBefore,
                fixture.enemy.getArbiter().getOverrideReason());
        assertSame(outcomeBefore, fixture.enemy.getLastActionOutcome());
    }

    // ────────── Arbiter-A03 ──────────

    /**
     * Arbiter-A03: when the remote agent is slow, the enemy continues the old plan.
     * Uses a PATROL lease with player not visible, so P3 is selected.
     */
    @Test
    public void old_plan_continues_while_agent_slow() {
        // Player far away, not visible
        Fixture fixture = fixture(1, new Position(1, 1),
                new Position(15, 1), 10);
        fixture.prime();

        // Adopt a remote PATROL intent targeting a visible walkable tile
        DecisionValidator.ValidationResult result = fixture.adoptPatrol(
                "decision-1", 0, new Position(5, 1));
        assertEquals(DecisionValidator.ValidationResult.ACCEPTED, result);

        // Execute first tick: P3 uses lease, plans and moves
        fixture.tick(0);
        Position posAfterTick0 = fixture.enemy.getPosition();
        assertEquals(new Position(2, 1), posAfterTick0);
        ActionOutcome outcome0 = fixture.enemy.getLastActionOutcome();
        assertEquals(AgentProtocol.DecisionSource.REMOTE_AGENT,
                outcome0.getDecisionSource());
        assertEquals("decision-1", outcome0.getDecisionId());

        // No new intent arrives (agent is slow). Execute second tick: P3 continues
        fixture.tick(1);
        Position posAfterTick1 = fixture.enemy.getPosition();
        assertEquals(new Position(3, 1), posAfterTick1);
        ActionOutcome outcome1 = fixture.enemy.getLastActionOutcome();
        assertEquals(AgentProtocol.DecisionSource.REMOTE_AGENT,
                outcome1.getDecisionSource());
        // Same decision, incremented action index
        assertEquals("decision-1", outcome1.getDecisionId());
        assertEquals(outcome0.getActionIndex() + 1, outcome1.getActionIndex());
    }

